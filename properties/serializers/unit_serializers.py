class RentAgreementDraftSerializer(serializers.ModelSerializer):
    """The agreement details the backend needs and the workflow state.

    The document itself is generated by the backend, so the file and every
    workflow field are read only here.
    """

    signature_progress = serializers.SerializerMethodField()
    status_label = serializers.SerializerMethodField()
    document_url = serializers.SerializerMethodField()

    class Meta:
        model = RentAgreementDraft
        fields = "__all__"
        read_only_fields = [
            "user",
            "generated_at",
            "file",
            "status",
            "status_label",
            "agreement_number",
            "document_generated_at",
            "document_url",
            "generation_error",
            "signature_progress",
            "owner_signed",
            "renter_signed",
            "owner_signed_at",
            "renter_signed_at",
            "sent_for_signature_at",
        ]

    @override
    def get_signature_progress(self, obj: RentAgreementDraft) -> int:
        """Return the share of the workflow that is signed, in percent."""
        return obj.signature_progress

    @override
    def get_status_label(self, obj: RentAgreementDraft) -> str:
        """Return the human readable status."""
        return dict(RentAgreementDraft.AgreementStatus.choices).get(
            obj.status, obj.status
        )

    @override
    def get_document_url(self, obj: RentAgreementDraft) -> str:
        """Return the path of the generated document, when there is one."""
        if not obj.file:
            return ""
        request = self.context.get("request")
        path = obj.file.url
        if request is not None:
            return request.build_absolute_uri(path)
        return path

    @override
    def validate(self, data: dict[str, Any]) -> dict[str, Any]:
        request_user = self.context["request"].user
        renter = data.get("renter") or getattr(self.instance, "renter", None)
        unit = data.get("unit") or getattr(self.instance, "unit", None)
        if not renter or not unit:
            raise serializers.ValidationError("Both renter and unit are required.")
        if unit.owner != request_user:
            raise serializers.ValidationError(NOT_UNIT_OWNER)
        if renter.unit != unit:
            raise serializers.ValidationError(
                "Renter does not belong to the selected unit."
            )
        start_date = data.get("start_date") or getattr(
            self.instance, "start_date", None
        )
        end_date = data.get("end_date") or getattr(self.instance, "end_date", None)
        if start_date and end_date and end_date < start_date:
            raise serializers.ValidationError(
                "The end date cannot be earlier than the start date."
            )
        return data
